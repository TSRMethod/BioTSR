#!/usr/bin/env python3
"""Generate the release-facing method capability matrix from the method registry.

``docs/CAPABILITY_MATRIX.md`` is **derived, never hand-written**: every cell is
read from ``biotsr.methods.registry`` (family, label domain, declared modifiers,
the standard profile each method runs under) and ``biotsr.methods.arguments``
(the target arguments each method reads), and every modifier cell is then
cross-checked against the method's own refusal logic -- a "yes" must be
accepted by ``Method.validate_modifiers`` and a "no" must be refused by it.  A
capability the registry and the refusal disagree about stops the script rather
than reaching the page.

Usage::

    python3 validation/scripts/capability_matrix.py          # rewrite the page
    python3 validation/scripts/capability_matrix.py --check  # exit 1 if stale

``tests/unit/test_release_readiness.py`` runs the ``--check`` comparison, so the
page cannot drift from the registry without the suite failing.
"""

from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WORKSPACE = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(WORKSPACE, "src")
PAGE = os.path.join(WORKSPACE, "docs", "CAPABILITY_MATRIX.md")

if SRC not in sys.path:
    sys.path.insert(0, SRC)

from biotsr.methods.arguments import (  # noqa: E402
    accepted_arguments,
    required_arguments,
)
from biotsr.methods.registry import get_method, list_methods  # noqa: E402

#: The modifiers a method can declare, in the order the page shows them.
MODIFIERS = (
    ("aa_grouping", "AA grouping"),
    ("mirror", "mirror"),
    ("size_filter", "size filter"),
    ("sse", "SSE"),
)

#: Label domain -> what a vertex is.  Read from the default profile's scheme.
VERTEX_BY_DOMAIN = {
    "protein_amino_acid": "Cα",
    "atom_element": "atomic",
}

FAMILY_ORDER = ("calpha", "atomic", "cross")


def _refuses(method, modifier):
    try:
        method.validate_modifiers({modifier})
    except ValueError:
        return True
    return False


def method_row(name):
    """One row of the matrix, as a dict of facts read from the package."""
    method = get_method(name)
    scheme = method.default_profile.label_scheme
    domain = getattr(scheme, "domain", None)
    domain = getattr(domain, "value", domain)
    if domain not in VERTEX_BY_DOMAIN:
        raise SystemExit("method %r: unrecognised label domain %r" % (name, domain))
    declared = set(method.supported_modifiers)
    modifiers = {}
    for key, _title in MODIFIERS:
        supported = key in declared
        if supported == _refuses(method, key):
            raise SystemExit(
                "method %r: registry declares %s=%s but validate_modifiers %s it"
                % (name, key, supported, "refuses" if not supported else "accepts")
            )
        modifiers[key] = supported
    accepted = tuple(accepted_arguments(method))
    required = tuple(required_arguments(method))
    if not set(required) <= set(accepted):
        raise SystemExit("method %r: requires %s but does not accept them"
                         % (name, sorted(set(required) - set(accepted))))
    return {
        "method": name,
        "family": method.family,
        "vertices": VERTEX_BY_DOMAIN[domain],
        "cross": method.family == "cross",
        "scope": method.scope,
        "label_scheme": scheme.name,
        "radix": method.default_profile.key_space().label_scheme.radix,
        "standard_profile": method.default_profile.name,
        "profile_description": method.default_profile.description,
        "modifiers": modifiers,
        "arguments": accepted,
        "required": required,
    }


def rows():
    out = [method_row(n) for n in list_methods()]
    unknown = sorted({r["family"] for r in out} - set(FAMILY_ORDER))
    if unknown:
        raise SystemExit("unrecognised method families: %s" % unknown)
    return sorted(out, key=lambda r: (FAMILY_ORDER.index(r["family"]), r["method"]))


def _yes(flag):
    return "yes" if flag else "—"


def _arguments(row):
    """Accepted target arguments in the registry's order; required ones bold."""
    if not row["arguments"]:
        return "— (the chain only)"
    return ", ".join(
        ("**`%s`**" if a in row["required"] else "`%s`") % a for a in row["arguments"]
    )


def render():
    table = rows()
    lines = [
        "# BioTSR — method capability matrix",
        "",
        "<!-- GENERATED by validation/scripts/capability_matrix.py from the",
        "     method registry. Do not edit by hand: run the script instead. The test",
        "     suite fails if this page and the registry disagree. -->",
        "",
        "BioTSR is the unified software implementation of the Triangular Spatial",
        "Relationship (TSR) methodology. This page lists every registered method and",
        "what it supports, read directly from the package's method registry and its",
        "table of target arguments. Each modifier cell is cross-checked against the",
        "method's own validation: a \"yes\" is accepted, and a \"—\" is refused with",
        "an error naming what the method does support. Every method runs under one",
        "standard profile; there is no profile to choose.",
        "",
        "**%d methods** — %s." % (
            len(table),
            ", ".join(
                "%d %s" % (sum(1 for r in table if r["family"] == f), f)
                for f in FAMILY_ORDER
            ),
        ),
        "",
        "| method | family | vertices | cross | %s | target arguments |" % (
            " | ".join(title for _k, title in MODIFIERS)
        ),
        "|---|---|---|---|%s---|" % ("---|" * len(MODIFIERS)),
    ]
    for r in table:
        lines.append(
            "| `%s` | %s | %s | %s | %s | %s |"
            % (
                r["method"],
                r["family"],
                r["vertices"],
                _yes(r["cross"]),
                " | ".join(_yes(r["modifiers"][k]) for k, _t in MODIFIERS),
                _arguments(r),
            )
        )
    lines += [
        "",
        "## Standard profile and key space per method",
        "",
        "| method | standard profile | label scheme | label radix | scope |",
        "|---|---|---|---|---|",
    ]
    for r in table:
        lines.append(
            "| `%s` | `%s` | `%s` | %d | `%s` |"
            % (r["method"], r["standard_profile"], r["label_scheme"], r["radix"], r["scope"])
        )
    lines += [
        "",
        "## Standard profiles",
        "",
    ]
    seen = set()
    for r in table:
        if r["standard_profile"] in seen:
            continue
        seen.add(r["standard_profile"])
        users = [x["method"] for x in table if x["standard_profile"] == r["standard_profile"]]
        lines += [
            "* **`%s`** (%s) — %s" % (
                r["standard_profile"],
                ", ".join("`%s`" % u for u in users),
                " ".join(r["profile_description"].split()),
            ),
        ]
    lines += [
        "",
        "## Reading the table",
        "",
        "* **vertices** — `Cα`: one point per residue, labelled by residue (the 20",
        "  regular amino acids and eleven supported modified residues);",
        "  `atomic`: one point per heavy atom, labelled by its element from the packaged element table.",
        "* **cross** — triangles are drawn across two user-named sides, and every",
        "  triangle has vertices on both.",
        "* **AA grouping** — the grouped residue labels (23 codes, radix 30). Defined only over",
        "  amino-acid labels, so only Cα methods offer it.",
        "* **mirror** — negate a key whose pre-fold angle exceeds 90°. Off by default.",
        "* **size filter** — keep triangles whose longest edge is below a cutoff. Off by",
        "  default.",
        "* **SSE** — the 18 secondary-structure categories. An annotation: it changes no",
        "  key and neither identity fingerprint.",
        "* **target arguments** — the arguments that say *what* to compute on, beyond",
        "  the chain; **bold** ones are required. Python takes them as keyword",
        "  arguments (`residue_types=`), the command line as flags with dashes",
        "  (`--residue-types`). An argument a method does not read is refused by",
        "  name rather than ignored.",
        "* **standard profile** — the fixed conventions (distance and angle schemes,",
        "  label scheme, admission rules) a method runs under. Modifiers vary a run;",
        "  the profile itself cannot be replaced.",
        "",
        "Candidate-strategy extensions (for example CA-kNN) are not part of BioTSR 1.0",
        "and are absent from the registry.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed page differs from the registry")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        try:
            with open(PAGE, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("%s is stale: regenerate it with %s"
                  % (os.path.relpath(PAGE, WORKSPACE), os.path.relpath(__file__, WORKSPACE)))
            return 1
        print("capability matrix matches the registry (%d methods)" % len(rows()))
        return 0
    os.makedirs(os.path.dirname(PAGE), exist_ok=True)
    with open(PAGE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s" % os.path.relpath(PAGE, WORKSPACE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
